#define BNO08X_I2C_ADDR 0x4A // Dirección I2C (ADDR = GND)

// Pines del sensor
#define BNO08X_RST_Pin   GPIO_PIN_8
#define BNO08X_RST_Port  GPIOA
#define BNO08X_PS1_Pin   GPIO_PIN_10
#define BNO08X_PS1_Port  GPIOB
#define BNO08X_PS0_Pin   GPIO_PIN_4
#define BNO08X_PS0_Port  GPIOB

// Convertir Q14 a float
float q14_to_float(int16_t q) {
    return ((float)q) / 16384.0f;
}

// Configuración mínima de pines
void BNO08X_ConfigPins(void) {
    GPIO_InitTypeDef GPIO_InitStruct = {0};

    __HAL_RCC_GPIOA_CLK_ENABLE();
    __HAL_RCC_GPIOB_CLK_ENABLE();

    GPIO_InitStruct.Pin = BNO08X_RST_Pin | BNO08X_PS1_Pin | BNO08X_PS0_Pin;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
    HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);

    // Configurar PS1=LOW, PS0=LOW para I2C
    HAL_GPIO_WritePin(BNO08X_PS1_Port, BNO08X_PS1_Pin, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(BNO08X_PS0_Port, BNO08X_PS0_Pin, GPIO_PIN_RESET);

    // Pulso de reset
    HAL_GPIO_WritePin(BNO08X_RST_Port, BNO08X_RST_Pin, GPIO_PIN_RESET);
    HAL_Delay(10);
    HAL_GPIO_WritePin(BNO08X_RST_Port, BNO08X_RST_Pin, GPIO_PIN_SET);
    HAL_Delay(50);
}

// Leer cuaterniones del sensor directamente por I2C
HAL_StatusTypeDef BNO08X_ReadQuat(I2C_HandleTypeDef *hi2c, float *qw, float *qx, float *qy, float *qz) {
    uint8_t buf[12];
    int16_t qw_i, qx_i, qy_i, qz_i;

    // Leer 12 bytes del sensor (X,Y,Z,W en Q14)
    if (HAL_I2C_Master_Receive(hi2c, (BNO08X_I2C_ADDR << 1), buf, 12, HAL_MAX_DELAY) != HAL_OK)
        return HAL_ERROR;

    qw_i = (int16_t)((buf[1] << 8) | buf[0]);
    qx_i = (int16_t)((buf[3] << 8) | buf[2]);
    qy_i = (int16_t)((buf[5] << 8) | buf[4]);
    qz_i = (int16_t)((buf[7] << 8) | buf[6]);

    *qw = q14_to_float(qw_i);
    *qx = q14_to_float(qx_i);
    *qy = q14_to_float(qy_i);
    *qz = q14_to_float(qz_i);

    return HAL_OK;
}

